#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();

function readTextOrEmpty(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const deps = Object.keys({
  ...pkg.dependencies,
  ...pkg.devDependencies,
}).toSorted();

function readLicenseText(depName) {
  const dir = join(root, "node_modules", depName);
  for (const candidate of ["LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING"]) {
    const raw = readTextOrEmpty(join(dir, candidate));
    if (raw) return raw.replace(/\r\n/g, "\n").trim();
  }
  let entries = [];
  try {
    entries = readdirSync(dir);
  } catch {
    return "";
  }
  for (const entry of entries) {
    if (/^(license|copying)/i.test(entry)) {
      const raw = readTextOrEmpty(join(dir, entry));
      if (raw) return raw.replace(/\r\n/g, "\n").trim();
    }
  }
  return "";
}

const rows = deps.map((name) => {
  const rawManifest = readTextOrEmpty(join(root, "node_modules", name, "package.json"));
  const depPkg = rawManifest ? JSON.parse(rawManifest) : { version: "unknown", license: "Unknown" };
  return {
    name,
    version: depPkg.version ?? "unknown",
    license: depPkg.license ?? "Unknown",
    text: readLicenseText(name),
  };
});

const lines = [
  "Third Party Notices",
  "",
  "Generated by tools/third-party-notices.mjs. Do not edit by hand.",
  `Direct Node packages linked: ${rows.length}`,
];

if (rows.length > 0) {
  lines.push("", "| Package | Version | License |", "|---|---|---|");
  for (const r of rows) {
    lines.push(`| ${r.name} | ${r.version} | ${r.license} |`);
  }
  rows.forEach((r, idx) => {
    if (r.text) {
      lines.push(
        "",
        `## License Text ${idx + 1}`,
        `Applies to: ${r.name} ${r.version}`,
        "",
        "```text",
        r.text,
        "```",
      );
    }
  });
}

const content = `${lines.join("\n")}\n`;
const out = join(root, "ThirdPartyNotices.txt");
if (process.argv.includes("--check")) {
  const current = readTextOrEmpty(out);
  if (current !== content) {
    console.error("FAIL notices: ThirdPartyNotices.txt is out of date. Run pnpm notices.");
    process.exit(1);
  }
  console.log(`PASS notices (${rows.length} direct packages)`);
} else {
  writeFileSync(out, content);
  console.log(`PASS notices: updated ThirdPartyNotices.txt (${rows.length} direct packages)`);
}
